import { REDIRECTS, PREFIX_REDIRECTS, GONE } from './redirectMap.mjs'

/**
 * Builds the site's .htaccess. ONE place decides every server-level rule so the file can never
 * drift from the redirect map (scripts/seo/redirectMap.mjs).
 *
 *   mode 'base'    — what `client/public/.htaccess` ships with EVERY build: legacy 301s, 410s,
 *                    trailing-slash strip, and the single-page-app fallback. Safe on any build,
 *                    including one made on the server without pre-rendering.
 *   mode 'release' — the same, plus real HTTP 404s: a path is valid only if a pre-rendered file
 *                    exists for it (dist/_pre/<route>.html, written by scripts/seo/prerender.mjs),
 *                    or it is a real file, or it belongs to a client-rendered area (app, login,
 *                    blog…). Everything else answers 404 with the pre-rendered 404 screen.
 *                    Only ever generated by the prerender step, which knows `_pre` exists.
 *
 * `origin` is the absolute site origin used as the redirect target host. Production = https://atoopv.com.
 * Passing '' makes every target host-relative (for a staging build).
 */
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

export const CLIENT_RENDERED_AREAS = ['app', 'login', 'register', 'forgot', 'verify-email', 'blog']

export function buildHtaccess({ mode = 'base', origin = 'https://atoopv.com' } = {}) {
  const to = (path) => `${origin}${path}`
  const lines = []
  const push = (...l) => lines.push(...l)

  push(
    '# ─────────────────────────────────────────────────────────────────────────────',
    '# ATOOPV — .htaccess   (React single-page app; API lives on api.atoopv.com)',
    '#',
    '# GENERATED by client/scripts/seo/htaccess.mjs from scripts/seo/redirectMap.mjs.',
    '# Do not edit by hand — change the map / generator and run `npm run seo:htaccess`.',
    '#',
    `# mode: ${mode}${mode === 'release' ? ' (pre-rendered routes + real 404s)' : ' (redirects + 410s + SPA fallback)'}`,
    '#',
    "# If cPanel ever adds its own Passenger block here (\"# DO NOT REMOVE. CLOUDLINUX PASSENGER",
    '# CONFIGURATION\") KEEP it and add the rules around it — never inside it.',
    '# ─────────────────────────────────────────────────────────────────────────────',
    '',
    'DirectoryIndex index.html',
    'Options -MultiViews',
    '',
    '<IfModule mod_rewrite.c>',
    '  RewriteEngine On',
    '',
    '  # 0. The API (incl. /api/socket.io) is never rewritten.',
    '  RewriteRule ^api(/|$) - [L]',
    '',
    '  # 1. Discontinued content and WordPress leftovers → HTTP 410 Gone (not a redirect to the',
    '  #    homepage: Google treats mass-redirects of dead pages to "/" as soft 404s).',
    `  RewriteRule ^(${GONE.exact.map(esc).join('|')})/?$ - [G,NC,L]`,
    `  RewriteRule ^(${GONE.prefixes.map((p) => esc(p.replace(/\/$/, ''))).join('|')})/ - [G,NC,L]`,
    '  RewriteRule (^|/)feed/?$ - [G,L]',
    '  RewriteRule ^(wp-[^/]*\\.php|xmlrpc\\.php)$ - [G,L]',
    '',
    '  # 2. Legacy URL → final URL, ONE hop, with or without trailing slash (query string kept).',
    '  #    Placed before the www/https canonicalisation so even http://www… reaches the target in',
    '  #    a single 301.',
  )
  for (const r of REDIRECTS) {
    const alt = r.from.length > 1 ? `(${r.from.map(esc).join('|')})` : esc(r.from[0])
    // Apache does not allow a trailing comment on a directive line — the note goes on its own line.
    if (r.note) push(`  # ${r.note}`)
    push(`  RewriteRule ^${alt}/?$ ${to(r.to)} [R=301,L]`)
  }
  push('', '  # 2b. Prefix redirects (WordPress taxonomy archives).')
  for (const p of PREFIX_REDIRECTS) {
    push(p.exact ? `  RewriteRule ^${esc(p.prefix)}/?$ ${to(p.to)} [R=301,L]` : `  RewriteRule ^${esc(p.prefix)} ${to(p.to)} [R=301,L]`)
  }
  push(
    '',
    '  # 2c. Renamed routes of this site: /atoopv and /atoopv/* moved to the top level.',
    `  RewriteRule ^atoopv/?$ ${to('/')} [R=301,L]`,
    `  RewriteRule ^atoopv/simulateur/?$ ${to('/tarification')} [R=301,L]`,
    `  RewriteRule ^atoopv/(.+?)/?$ ${to('/$1')} [R=301,L]`,
    '',
    '  # 3. www → apex, always over HTTPS (one redirect, not two).',
    '  RewriteCond %{HTTP_HOST} ^www\\.atoopv\\.com$ [NC]',
    '  RewriteRule ^ https://atoopv.com%{REQUEST_URI} [L,R=301]',
    '',
    '  # 4. Enforce HTTPS (also honours a TLS-terminating proxy that sets X-Forwarded-Proto).',
    '  RewriteCond %{HTTPS} !=on',
    '  RewriteCond %{HTTP:X-Forwarded-Proto} !=https',
    '  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]',
    '',
    '  # 5. Trailing slash: any other URL ending in "/" → same URL without it (never the root,',
    '  #    never a real directory such as /assets/).',
    '  RewriteCond %{REQUEST_FILENAME} !-d',
    `  RewriteRule ^(.+)/$ ${to('/$1')} [R=301,L]`,
    '',
  )

  if (mode === 'release') {
    push(
      '  # 6. Real files (assets, images, sitemap.xml, robots.txt…) are served as they are.',
      '  RewriteCond %{REQUEST_FILENAME} -f',
      '  RewriteRule ^ - [L]',
      '',
      '  # 7. Client-rendered areas: private screens and database-backed blog posts. These stay a',
      '  #    single-page app (noindex or not enumerable at build time).',
      `  RewriteRule ^(${CLIENT_RENDERED_AREAS.join('|')})(/|$) /index.html [L]`,
      '',
      '  # 8. Public routes are pre-rendered at build time: the file IS the whitelist of valid URLs.',
      '  RewriteRule ^$ /_pre/index.html [L]',
      '  RewriteCond %{DOCUMENT_ROOT}/_pre/$1.html -f',
      '  RewriteRule ^(.+)$ /_pre/$1.html [L]',
      '',
      '  # 9. Everything else does not exist → a real HTTP 404 (body: the 404 screen, see ErrorDocument).',
      '  RewriteRule ^ - [R=404,L]',
      '</IfModule>',
      '',
      'ErrorDocument 404 /_pre/404.html',
      'ErrorDocument 410 /_pre/404.html',
    )
  } else {
    push(
      '  # 6. Single-page-app fallback: real files/directories are served as-is; every other URL',
      '  #    is handed to React Router.',
      '  RewriteCond %{REQUEST_FILENAME} !-f',
      '  RewriteCond %{REQUEST_FILENAME} !-d',
      '  RewriteRule ^ /index.html [L]',
      '</IfModule>',
    )
  }

  push(
    '',
    '<IfModule mod_headers.c>',
    '  # The HTML shells must never be cached, otherwise visitors keep an old build after a deploy.',
    '  <FilesMatch "\\.html$">',
    '    Header set Cache-Control "no-cache, must-revalidate"',
    '  </FilesMatch>',
    '  Header always set X-Content-Type-Options "nosniff"',
    '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
    '  Header always set X-Frame-Options "SAMEORIGIN"',
    '</IfModule>',
    '',
    '<IfModule mod_deflate.c>',
    '  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml',
    '</IfModule>',
    '',
  )
  return lines.join('\n')
}
